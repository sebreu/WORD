// Randomizes each word independently. Adjacent duplicates are rejected.
export function createChallenge(wordCount = 300) {
  const result = [];
  let previous = '';
  const random = new Uint32Array(1);
  for (let i = 0; i < wordCount; i += 1) {
    let word;
    do {
      crypto.getRandomValues(random);
      word = WORDS[random[0] % WORDS.length];
    } while (word === previous);
    result.push(word);
    previous = word;
  }
  return result.join(' ');
}
